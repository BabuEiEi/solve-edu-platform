import { test, expect } from './fixtures.js'
import { signIn, watchCsp, IDS, answerDialog } from './helpers.js'

const PICTURE = 'supabase/seed-media/assessment-media/a1000000-0000-4000-a000-000000000002/afl-cycle.png'

test('trainer builds dropdown, cloze and image-labelling items (real upload, tap to place); trainee scores 3/3', async ({
  browser,
}) => {
  const trainer = await (await browser.newContext()).newPage()
  const csp = watchCsp(trainer)
  await signIn(trainer, 'trainer@example.test')
  await trainer.goto(`/#/courses/${IDS.course}/quizzes`)
  const create = trainer.locator('form[data-form=create-quiz]')
  await create.locator('[name=code]').fill('E2E-BLANKS')
  await create.locator('[name=title]').fill('ข้อสอบช่องว่างและรูป (E2E)')
  await create.getByRole('button', { name: 'สร้างแบบทดสอบ' }).click()
  await expect(trainer.getByRole('heading', { name: 'ข้อสอบช่องว่างและรูป (E2E)' })).toBeVisible()

  // Dropdown: one blank already in the text, a second inserted at the end
  await trainer.locator('[data-action=new-item][data-type=dropdown]').click()
  let form = trainer.locator('form[data-form=item]')
  await form.locator('[name=prompt]').fill('เลือกคำ')
  const text = form.locator('[data-template]')
  await text.fill('การประเมิน {{b1}} ใช้เพื่อ ')
  await text.press('End')
  await form.getByRole('button', { name: '+ แทรกช่อง' }).click()
  await expect(text).toHaveValue('การประเมิน {{b1}} ใช้เพื่อ {{b2}}')
  await form.locator('[name=bopt_b1_text]').nth(0).fill('ระหว่างเรียน')
  await form.locator('[name=bopt_b1_text]').nth(1).fill('ปลายภาค')
  await form.locator('[name=bopt_b2_text]').nth(0).fill('จัดอันดับ')
  await form.locator('[name=bopt_b2_text]').nth(1).fill('ปรับการสอน')
  await form.locator('[name=bkey_b1][value=a]').check()
  await form.locator('[name=bkey_b2][value=b]').check()
  await form.getByRole('button', { name: 'บันทึกข้อ' }).click()
  await expect(trainer.getByText('บันทึกข้อแล้ว')).toBeVisible()

  // Cloze: a text blank and a number blank
  await trainer.locator('[data-action=new-item][data-type=cloze]').click()
  form = trainer.locator('form[data-form=item]')
  await form.locator('[name=prompt]').fill('เติมคำ')
  await form.locator('[data-template]').fill('คำย่อคือ {{b1}} ร้อยละ ')
  await form.locator('[data-template]').press('End')
  await form.getByRole('button', { name: '+ แทรกช่อง' }).click()
  await form.locator('[name=bacc_b1]').fill('AfL\nเอเอฟแอล')
  await form.locator('[data-blank-row=b2] [data-blank-kind]').selectOption('number')
  await form.locator('[name=bval_b2]').fill('75')
  await form.getByRole('button', { name: 'บันทึกข้อ' }).click()
  await expect(trainer.getByText('บันทึกข้อแล้ว')).toBeVisible()

  // Image labelling: upload the picture, tap two places on it, label them
  await trainer.locator('[data-action=new-item][data-type=image_labelling]').click()
  form = trainer.locator('form[data-form=item]')
  await form.locator('[name=prompt]').fill('ติดป้าย')
  const picker = form.locator('[data-file-picker]', { has: trainer.locator('[name=media_file]') })
  await expect(picker).toContainText('เลือกรูป…') // Thai, not the browser's "Choose File"
  await expect(picker.locator('[data-file-name]')).toHaveText('ยังไม่ได้เลือกไฟล์')
  await form.locator('[name=media_file]').setInputFiles(PICTURE)
  await expect(picker.locator('[data-file-name]')).toHaveText('afl-cycle.png')
  const picture = form.locator('[data-label-image]')
  await expect(picture).toBeVisible()
  const box = await picture.boundingBox()
  await picture.click({ position: { x: box.width * 0.21, y: box.height * 0.25 } })
  await picture.click({ position: { x: box.width * 0.8, y: box.height * 0.35 } })
  await expect(form.locator('[data-dot]')).toHaveCount(2)
  const labels = form.locator('[name=labels_text]')
  await labels.nth(0).fill('กำหนดเป้าหมาย')
  await labels.nth(1).fill('รวบรวมหลักฐาน')
  await labels.nth(2).fill('ตัดเกรด')
  await form.locator('select[data-key-select]').nth(0).selectOption({ label: 'กำหนดเป้าหมาย' })
  await form.locator('select[data-key-select]').nth(1).selectOption({ label: 'รวบรวมหลักฐาน' })
  await form.getByRole('button', { name: 'บันทึกข้อ' }).click()
  await expect(trainer.getByText('พร้อมเผยแพร่ (3 ข้อ)')).toBeVisible()
  await trainer.locator('[data-action=publish]').click()

  await answerDialog(trainer)
  await expect(trainer.getByText(/เผยแพร่แล้ว/).first()).toBeVisible()
  await trainer.locator('a[data-action-link=assign]').click()
  const a = trainer.locator('form[data-form=assignment]')
  await a.locator('[name=purpose]').selectOption('formative')
  await a.locator('[name=title]').fill('ช่องว่างและรูป (E2E)')
  await a.locator('[name=close_at]').fill('2027-03-31T16:00')
  await a.getByRole('button', { name: 'บันทึกและเผยแพร่' }).click()
  await expect(trainer.getByRole('heading', { name: 'ช่องว่างและรูป (E2E)' })).toBeVisible()
  expect(csp).toEqual([])

  const learner = await (await browser.newContext()).newPage()
  await signIn(learner, 'teacher.a1@example.test')
  await learner.goto('/#/assessments')
  await learner.getByRole('link', { name: /ช่องว่างและรูป \(E2E\)/ }).click()
  await learner.getByRole('button', { name: 'เริ่มทำแบบทดสอบ' }).click()
  const dd = learner.locator('fieldset[data-item-type=dropdown]')
  await dd.getByLabel('ช่องที่ 1').selectOption({ label: 'ระหว่างเรียน' })
  await dd.getByLabel('ช่องที่ 2').selectOption({ label: 'ปรับการสอน' })
  const cz = learner.locator('fieldset[data-item-type=cloze]')
  await cz.getByLabel('ช่องที่ 1').fill('เอเอฟแอล')
  await cz.getByLabel('ช่องที่ 2').fill('75')
  const lb = learner.locator('fieldset[data-item-type=image_labelling]')
  await expect(lb.locator('img')).toBeVisible()
  await lb.getByLabel('คำตอบของ จุดที่ 1').selectOption({ label: 'กำหนดเป้าหมาย' })
  await lb.getByLabel('คำตอบของ จุดที่ 2').selectOption({ label: 'รวบรวมหลักฐาน' })
  await learner.getByRole('button', { name: 'ส่งคำตอบ' }).click()
  await expect(learner.getByRole('heading', { name: 'ผลการทดสอบ' })).toBeVisible()
  await expect(learner.locator('[data-score]')).toHaveText(/3\s*\/\s*3/)
})
